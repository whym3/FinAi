import { Download, Play } from 'lucide-react'
import { Button } from '@/components/ui/button'
import { Card, CardHeader, PageHeader, Q } from '@/components/pravah'
import { useSession } from '@/app/session'
import { useAct, useReports } from '@/mock/hooks'
import * as api from '@/mock/api'
import { dateTime } from '@/lib/format'
import { downloadCsv } from '@/lib/csv'

export default function ReportsPage() {
  const q = useReports()
  const { entity, user } = useSession()
  const { act } = useAct()
  return (
    <>
      <PageHeader title="Reports" sub={`Statutory, tax and management reports for ${entity.name}.`} />
      <Q q={q}>{reports => (
        <div className="grid grid-cols-[repeat(auto-fill,minmax(360px,1fr))] gap-4">
          {[...new Set(reports.map(r => r.group))].map(g => (
            <Card key={g}>
              <CardHeader title={g} as="h3" />
              {reports.filter(r => r.group === g).map(r => (
                <div key={r.id} className="flex items-start gap-3 border-b border-border px-4 py-3 last:border-b-0">
                  <div className="min-w-0 flex-1"><div className="text-xs font-medium">{r.name}</div><div className="text-[11px] text-text-2">{r.description}</div><div className="mt-0.5 text-[11px] text-text-3">{r.format}{r.lastRun ? ` · last run ${dateTime(r.lastRun)}` : ' · never run'}</div></div>
                  <Button size="sm" onClick={async () => { const done = await act(() => api.runReport(r.id, entity.id, user.id), `${r.name} generated`); if (done) downloadCsv(`${r.name.toLowerCase().replace(/[^a-z0-9]+/g, '-')}.csv`, ['Report', 'Entity', 'Generated by'], [[r.name, entity.name, user.name]]) }}>{r.lastRun ? <Download /> : <Play />}{r.lastRun ? 'Run again' : 'Run'}</Button>
                </div>
              ))}
            </Card>
          ))}
        </div>
      )}</Q>
    </>
  )
}
